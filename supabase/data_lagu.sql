-- Jalankan di Supabase SQL Editor untuk membuat tabel master data_lagu anti-duplikasi.

create table if not exists public.data_lagu (
  id bigint generated by default as identity primary key,
  judul_lagu text not null check (length(trim(judul_lagu)) > 0),
  header_buku text,
  teks_reff text,
  teks_ayat_1 text not null check (length(trim(teks_ayat_1)) > 0),
  json_ayat_tambahan text default '[]',
  susunan_nyanyi text default 'ayat-only',
  -- Kunci normalisasi otomatis agar duplikat beda spasi/huruf/format PS-MB ditolak DB
  dedup_key text generated always as (
    lower(regexp_replace(trim(judul_lagu), '\s+', ' ', 'g'))
    || '||' ||
    trim(
      regexp_replace(
        regexp_replace(
          lower(regexp_replace(trim(coalesce(header_buku, '')), '\s+', ' ', 'g')),
          '^(puji syukur|ps)\.?\s*(no\.?\s*)?(?=[0-9]|$)',
          'ps '
        ),
        '^(madah bh?akti|mb)\.?\s*(no\.?\s*)?(?=[0-9]|$)',
        'mb '
      )
    )
  ) stored,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint data_lagu_dedup_key_unique unique (dedup_key)
);

create index if not exists idx_data_lagu_judul on public.data_lagu (judul_lagu);
create index if not exists idx_data_lagu_header on public.data_lagu (header_buku);

-- Update updated_at otomatis setiap baris diperbarui lewat upsert/edit
create or replace function public.set_data_lagu_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_data_lagu_updated_at on public.data_lagu;
create trigger trg_data_lagu_updated_at
before update on public.data_lagu
for each row execute function public.set_data_lagu_updated_at();

-- Samakan akses publik dengan tabel jadwal_misa dan lagu_misa (perketat jika sudah pakai Supabase Auth)
alter table public.data_lagu enable row level security;

drop policy if exists "data_lagu_public_all" on public.data_lagu;
create policy "data_lagu_public_all"
on public.data_lagu
for all
to anon, authenticated
using (true)
with check (true);
